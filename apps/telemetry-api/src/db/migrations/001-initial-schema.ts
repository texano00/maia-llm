/**
 * Generated primary key. SQLite needs `AUTOINCREMENT` to avoid reusing ids of
 * deleted rows; PostgreSQL and MySQL use their own identity syntax.
 *
 * This is the only place where the schema has to branch by dialect — every
 * other table, column, index and constraint below is ANSI SQL.
 */
function autoId(dialect: SqlDialect): string {
  switch (dialect) {
    case "sqlite":
      return "INTEGER PRIMARY KEY AUTOINCREMENT";
    case "postgres":
      return "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY";
    case "mysql":
      return "BIGINT PRIMARY KEY AUTO_INCREMENT";
  }
}

