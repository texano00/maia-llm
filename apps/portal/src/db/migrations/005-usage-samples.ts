import type { SqlDialect } from "../database.js";
import type { Migration } from "../migrate.js";

function autoId(dialect: SqlDialect): string {
  switch (dialect) {
    case "sqlite":
      return "INTEGER PRIMARY KEY AUTOINCREMENT";
    case "postgres":
      return "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY";
    case "mysql":
      return "BIGINT PRIMARY KEY AUTO_INCREMENT";
  }
}

/**
 * Opt-in, content-free measurements: one row per completed model run. Addresses
 * are stored in full (product decision) and never appear in logs; a separate
 * table records the installation preference so opt-out survives later samples.
 */
export const usageSamples: Migration = {
  id: 5,
  name: "usage-samples",
  statements: (dialect) => [
    `CREATE TABLE IF NOT EXISTS usage_samples (
      id ${autoId(dialect)},
      installation_id TEXT NOT NULL,
      app_version TEXT NOT NULL,
      os TEXT NOT NULL,
      os_version TEXT NOT NULL,
      arch TEXT NOT NULL,
      device_class TEXT NOT NULL,
      model_id TEXT NOT NULL,
      capability TEXT NOT NULL,
      output_tokens INTEGER NULL,
      generation_ms INTEGER NULL,
      tokens_per_second REAL NULL,
      outcome TEXT NOT NULL,
      occurred_at TEXT NOT NULL,
      observed_address TEXT NOT NULL,
      received_at TEXT NOT NULL
    )`,
    `CREATE INDEX IF NOT EXISTS usage_samples_installation
      ON usage_samples (installation_id, received_at)`,
    `CREATE INDEX IF NOT EXISTS usage_samples_model
      ON usage_samples (model_id, received_at)`,
    `CREATE INDEX IF NOT EXISTS usage_samples_received
      ON usage_samples (received_at)`,

    `CREATE TABLE IF NOT EXISTS usage_installations (
      installation_id TEXT NOT NULL PRIMARY KEY,
      opted_out INTEGER NOT NULL DEFAULT 0,
      updated_at TEXT NOT NULL
    )`,
  ],
};
