import type { SqlDialect } from "../database.js";
import type { Migration } from "../migrate.js";

function autoId(dialect: SqlDialect): string {
  switch (dialect) {
    case "sqlite":
      return "INTEGER PRIMARY KEY AUTOINCREMENT";
    case "postgres":
      return "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY";
    case "mysql":
      return "BIGINT PRIMARY KEY AUTO_INCREMENT";
  }
}

/**
 * Failed start-ups reported by desktop clients.
 *
 * Every column here answers a question the app could not answer on its own: the
 * container log dies with the instance, so `root_cause` and `log_tail` are the
 * only record of *why* vLLM's engine core died.
 */
export const failureReports: Migration = {
  id: 2,
  name: "failure-reports",
  statements: (dialect) => [
    `CREATE TABLE IF NOT EXISTS failure_reports (
      id ${autoId(dialect)},
      received_at TEXT NOT NULL,
      occurred_at TEXT NULL,
      app_version TEXT NOT NULL,
      platform TEXT NOT NULL,
      stage TEXT NOT NULL,
      model_id TEXT NULL,
      gpu_name TEXT NULL,
      machine_id INTEGER NULL,
      instance_id INTEGER NULL,
      attempt INTEGER NULL,
      attempts_total INTEGER NULL,
      error_class TEXT NOT NULL,
      error_message TEXT NOT NULL,
      root_cause TEXT NULL,
      memory_note TEXT NULL,
      model_failure TEXT NULL,
      context_scale REAL NULL,
      log_tail TEXT NULL
    )`,
    `CREATE INDEX IF NOT EXISTS failure_reports_received_at
      ON failure_reports (received_at)`,
    `CREATE INDEX IF NOT EXISTS failure_reports_model_id
      ON failure_reports (model_id)`
  ]
};
